import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { bundle } from '../../scripts/build-webkit.js';
import { createPageObserverScript } from '../../src/page-observer.js';

// Builds the DeepSeek Harness plugin package `dsh-chatgpt-panel` into dist/dsh-chatgpt-panel/
// (or the folder given as the first argument). The compiler, bridge and page observer are the
// repository's own modules, bundled exactly as scripts/build-webkit.js bundles them for the
// macOS app; nothing here forks them.
const here = fileURLToPath(new URL('./', import.meta.url));
const root = path.resolve(here, '../..');
const out = path.resolve(process.argv[2] ?? path.join(root, 'dist/dsh-chatgpt-panel'));

/** A dependency-free ES module as plain script text: its `export` keywords removed. */
async function inline(file) {
  const source = await readFile(path.join(here, file), 'utf8');
  const body = source.replace(/^export (?=(?:async )?function |const |class )/gmu, '');
  if (/^\s*(?:import|export)\b/mu.test(body)) throw new Error(`Unbundled syntax in ${file}`);
  return body;
}

export async function preload() {
  const template = await readFile(path.join(here, 'helper/preload.template.cjs'), 'utf8');
  const bridge = await bundle();
  const observer = `function () {\n${createPageObserverScript()}\n}`;
  if (!template.includes('__BRIDGE__;') || !template.includes('__OBSERVER__'))
    throw new Error('preload.template.cjs lost its placeholders');
  // Function replacers: the bundles contain `$` sequences that string replacements would expand.
  return template
    .replace('__BRIDGE__;', () => bridge)
    .replace('__OBSERVER__', () => observer)
    .replace(/^/u, '// Generated by plugins/deepseek-harness/build.js. Do not edit.\n');
}

export async function client() {
  const id = 'dsh-chatgpt-panel';
  return `;(() => {\n${await inline('shared/append.js')}\n${await inline('client/panel.js')}\nwindow.__ModuleLoader__.load({ id: '${id}', factory: (require) => createClient(require) });\n})();\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await rm(out, { recursive: true, force: true });
  await mkdir(path.join(out, 'client'), { recursive: true });
  await mkdir(path.join(out, 'helper'), { recursive: true });
  for (const entry of ['package.json', 'cordis.patch.yml', 'README.md', 'locale', 'host', 'shared'])
    await cp(path.join(here, entry), path.join(out, entry), { recursive: true });
  for (const entry of ['package.json', 'main.js', 'chat.js'])
    await cp(path.join(here, 'helper', entry), path.join(out, 'helper', entry));
  await cp(path.join(root, 'artifacts/app-icon.png'), path.join(out, 'icon.png'));
  await writeFile(path.join(out, 'helper/preload.cjs'), await preload());
  await writeFile(path.join(out, 'client/client.js'), await client());
  process.stdout.write(`Built ${out}\n`);
}
